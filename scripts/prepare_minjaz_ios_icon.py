#!/usr/bin/env python3
"""Render the existing MINJAZ vector artwork as an opaque 1024px iOS icon.

The source of truth is public/icon.svg. The PNG generated by this script is
ignored by Git, keeping the repository text-only for connector based updates.
This does not invent a new brand or add alpha that App Store rejects.
"""
from __future__ import annotations

from io import BytesIO
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public" / "icon.svg"
OUTPUT = ROOT / "ios-minjaz" / "Sources" / "Assets.xcassets" / "AppIcon.appiconset" / "Minjaz-1024.png"

def main() -> None:
    from PIL import Image
    if not SOURCE.is_file():
        raise SystemExit("Missing official MINJAZ public/icon.svg")
    svg = SOURCE.read_text(encoding="utf-8")
    if "<svg " not in svg or 'viewBox="0 0 512 512"' not in svg:
        raise SystemExit("Unexpected MINJAZ icon source")
    rendered = subprocess.run(
        ["rsvg-convert", "--width", "1024", "--height", "1024", str(SOURCE)],
        check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    ).stdout
    with Image.open(BytesIO(rendered)) as raster:
        if raster.size != (1024, 1024):
            raise SystemExit("Unexpected app icon dimensions")
        canvas = Image.new("RGB", raster.size, (17, 21, 42))
        canvas.paste(raster.convert("RGBA"), mask=raster.convert("RGBA").getchannel("A"))
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        canvas.save(OUTPUT, format="PNG", optimize=True)
    with Image.open(OUTPUT) as check:
        if check.mode != "RGB" or check.size != (1024, 1024):
            raise SystemExit("App icon must be opaque RGB 1024x1024")
    print("MINJAZ_IOS_APP_ICON_OK: 1024x1024 opaque RGB")

if __name__ == "__main__":
    main()
